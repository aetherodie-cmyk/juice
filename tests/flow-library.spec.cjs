test('flow-library restore accepts only an empty store and preserves existing data on failure',async({page})=>{
  await page.route('https://cdn.jsdelivr.net/**',route=>route.abort());
  await page.goto('/workspace.html');
  await expect(page.getByRole('button',{name:'展開 OMG',exact:true})).toBeVisible();
  await page.locator('#nativeMenu > summary').click();
  await page.getByRole('button',{name:'流程知識庫',exact:true}).click();
  const input=page.locator('input[type=file][accept=".json,application/json"]').last();
  await input.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{bad')});
  await expect(page.locator('#message')).toContainText('JSON');
  const raw=await page.evaluate(()=>{
    const Core=window.JuiceFlowLibraryCore;
    return Core.serialize(Core.createFlow(Core.blank(),{id:'flow-one',title:'備份流程',source:'flowchart LR\n A --> B',createdAt:'2026-10-26T00:00:00.000Z'}));
  });
  page.once('dialog',dialog=>dialog.accept());
  await input.setInputFiles({name:'library.json',mimeType:'application/json',buffer:Buffer.from(raw)});
  await expect(page.locator('#flowLibraryDialog')).toContainText('備份流程');
  page.once('dialog',dialog=>dialog.accept());
  await input.setInputFiles({name:'library.json',mimeType:'application/json',buffer:Buffer.from(raw)});
  await expect(page.locator('#message')).toContainText('僅可還原到空白流程庫');
  expect(await page.evaluate(()=>window.JuiceFlowLibraryStore.read())).toEqual(JSON.parse(raw));
});

