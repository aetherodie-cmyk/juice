test('source-board flow imports without changing the raw board and removing its reference keeps the master',async({page})=>{
  await page.route('https://cdn.jsdelivr.net/**',route=>route.abort());
  await page.goto('/workspace.html');
  await expect(page.getByRole('button',{name:'展開 OMG',exact:true})).toBeVisible();
  const board=await page.evaluate(()=>window.JuiceNested.seed());
  board.board.cards[0].blocks.push({id:'legacy-flow',type:'diagram',html:'flowchart LR\n A[接單] --> B[客製單]',aiContext:'{"questions":[]}'});
  await page.locator('#file').setInputFiles({name:'source-board.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(board))});
  await clickData(page,'#save');
  await page.locator('#nativeMenu > summary').click();
  await page.getByRole('button',{name:'流程知識庫'}).click();
  await page.getByRole('button',{name:'導入本白板既有流程'}).click();
  await page.getByRole('button',{name:'建立主檔並引用'}).click();
  await expect(page.locator('[data-flow-reference-id]')).toHaveCount(1);
  const catalog=await page.evaluate(()=>window.JuiceFlowLibraryStore.read());
  expect(catalog.flows[0].versions[0].source).toContain('接單');
  expect(catalog.flows[0].versions[0].aiContext).toBe('{"questions":[]}');
  expect((await page.evaluate(()=>JSON.parse(localStorage.getItem('juice-nested-prototype-v1')))).board).toEqual(board.board);
  await page.locator('[data-flow-reference-id]').getByRole('button',{name:'全畫面閱讀／編輯'}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'移除此處引用'}).click();
  await expect(page.locator('[data-flow-reference-id]')).toHaveCount(0);
  const after=await page.evaluate(()=>window.JuiceFlowLibraryStore.read());
  expect(after.flows).toHaveLength(1);
  expect(after.references).toHaveLength(0);
});

test('concurrent IndexedDB flow transactions serialize without dropping masters',async({page})=>{
  await page.goto('/workspace.html');
  const catalog=await page.evaluate(async()=>{
    const Core=window.JuiceFlowLibraryCore,Store=window.JuiceFlowLibraryStore;
    await Promise.all(['first','second'].map(id=>Store.transact(value=>Core.createFlow(value,{id,title:id,source:'flowchart LR\n A --> B',createdAt:'2026-10-26T00:00:00.000Z'}))));
    return Store.read();
  });
  expect(catalog.flows.map(flow=>flow.id).sort()).toEqual(['first','second']);
  expect(catalog.revision).toBe(2);
});

